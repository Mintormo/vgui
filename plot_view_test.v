module vgui

import math

// PlotView: разбор CSV (аудит 2026-10, 2.20). Нечисловое поле давало 0 вместо NaN, и
// строка с текстом становилась ложной точкой (0, 0). Подписи делений: крайняя подпись
// по Y вылезала за верхнюю рамку виджета (23.10.2026). Без окна и SDL.
//
// Запуск (из корня vgui): v test plot_view_test.v

fn test_csv_number_parsing() {
	assert csv_parse_number('1.5', ',') == f32(1.5)
	assert csv_parse_number(' 2,5 ', ';') == f32(2.5)
	assert csv_parse_number('"3"', ',') == f32(3)
	assert math.is_nan(f64(csv_parse_number('n/a', ',')))
	assert math.is_nan(f64(csv_parse_number('', ',')))
}

fn test_csv_skips_non_numeric_rows() {
	text := 'x,y\n1,2\nbad,row\n3,4\n'
	pts := parse_csv_points(text, ',', false, 0, 1) // заголовок не объявлен - тоже пропуск
	assert pts.len == 2
	assert pts[1].x == 3 && pts[1].y == 4
}

// Подпись деления рисуется, только если деление в области графика и подпись целиком
// внутри виджета: раньше верхняя подпись по Y (деление на краю графика, центр подписи
// на линии) половиной высоты торчала над рамкой.
fn test_tick_label_fits() {
	// деление на верхнем краю графика (y = 12), подпись высотой 20 - с 2 до 22: влезает
	assert tick_label_fits(12, 12, 200, 2, 20, 1, 260)
	// тот же край при поле сверху 6 (как было): подпись с -4 - за рамкой, не рисуем
	assert !tick_label_fits(6, 6, 200, -4, 20, 1, 260)
	// деление чуть вне графика (раньше допуск 10 px) - не подписывается
	assert !tick_label_fits(3, 12, 200, -7, 20, 1, 260)
	// погрешность пересчёта координат (0.3 px за краем) - подписывается
	assert tick_label_fits(11.7, 12, 200, 1.7, 20, 1, 260)
	// по X: подпись правого деления заходит на полосу прокрутки (area_hi = 300) - нет
	assert !tick_label_fits(298, 48, 298, 292, 12, 1, 300)
	assert tick_label_fits(290, 48, 298, 284, 12, 1, 300)
}
