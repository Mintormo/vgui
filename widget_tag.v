module vgui

// ═══════════════════════════════════════════════════════
// Тег типа виджета (аудит 3.B)
// ═══════════════════════════════════════════════════════
//
// Через C-ABI виджет приходит парой (voidptr, kind int): целое число даёт
// Python-класс, а указатель — сырой адрес. До появления тега `kind` был
// непроверяемым обещанием: неверное число в стороннем классе, сырой handle
// из `tree.widget("id")` или ошибка в другом языке-биндинге приводили к
// приведению чужой памяти к &Label и тихой её порче.
//
// Решение — общий заголовок: первое поле каждой структуры виджета
// объявлено как `type_tag int = kind_<name>`. Значение по умолчанию
// проставляется V при любом создании (фабрика, голый литерал `&Label{}`,
// сборка из YAML в ui_builder.v), поэтому отдельного шага «не забыть
// проставить тег» в фабриках нет.
//
// Так как поле объявлено первым, оно лежит по смещению 0, и тег можно
// прочитать, не зная типа, — через WidgetTagHeader. Инвариант смещения
// проверяется в widget_tag_test.v для каждого из типов: тест создаёт
// виджет и сверяет прочитанный тег с ожидаемым kind.
//
// Проверка стоит одно сравнение на вызов и живёт в vgui_resolve_widget —
// единственной точке приведения (ptr, kind) к типизированному указателю.
// Несовпадение тега — не паника, а `none`: capi-функция вернёт 0, а
// Python-обёртка превратит 0 в TypeError (см. `_check_added`).
//
// Добавляя виджет, не забудьте `type_tag int = kind_<name>` ПЕРВЫМ полем
// структуры и строку в widget_tag_test.v — иначе виджет не пройдёт
// проверку и не добавится ни в один контейнер.

// WidgetTagHeader — общий префикс любой структуры виджета.
struct WidgetTagHeader {
pub mut:
	type_tag int
}

// widget_type_tag — прочитать тег типа по сырому указателю на виджет.
// Возвращает 0 для nil. Указатель обязан указывать на структуру виджета:
// для произвольной памяти результат — просто первые четыре байта.
pub fn widget_type_tag(ptr voidptr) int {
	if ptr == unsafe { nil } {
		return 0
	}
	return unsafe { &WidgetTagHeader(ptr) }.type_tag
}

// widget_tag_matches — совпадает ли тег виджета с заявленным kind.
pub fn widget_tag_matches(ptr voidptr, kind int) bool {
	return widget_type_tag(ptr) == kind
}
